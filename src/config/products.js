export function getProductBySlug(slug) {
  return PRODUCTS.find((p) => p.slug === slug);
}

/**
 * Products that belong to a category-tree node.
 *  - A ROOT node (e.g. "electric-golf-buggies") returns every product whose
 *    `category` is that root, i.e. the whole family incl. its subcategories.
 *  - A SUBCATEGORY node (e.g. "remote-control-golf-buggies") returns products
 *    whose `subcategory` is that slug. Subcategory slugs are unique in the tree.
 *  - "used-golf-buggies" additionally cross-lists every Used / Ex-Demo product.
 */
export function getProductsByCategory(categorySlug) {
  if (!categorySlug) return [];
  const clean = categorySlug.replace(/^\/|\/$/g, '');
  return PRODUCTS.filter((p) => {
    if (p.category === clean || p.subcategory === clean) return true;
    if (clean === 'used-golf-buggies') return p.condition === 'Used' || p.condition === 'Ex-Demo';
    return false;
  });
}

export function getProductsByBrand(brandSlug) {
  return PRODUCTS.filter((p) => p.brand === brandSlug);
}

export function getFeaturedProducts() {
  return PRODUCTS.filter((p) => p.featured);
}
